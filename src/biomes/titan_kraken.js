  function getCurrentAt(x, y, z, timeOfDay, out) {
    const v = out || _cur;
    const depth = Math.max(0, -y);
    /* Прилив Сатурна поднимает уровень морей Титана примерно на метр и
       гонит воду вдоль оси моря; период — около 16 земных суток. */
    const t = (OC.uTime ? OC.uTime.value : 0) * 0.0026;
    const tide = Math.sin(t) * 0.42;
    v.set(tide, 0, 0);

    // Сток эстуария: течение вдоль канала к котловине
    const est = Math.exp(-Math.pow((z - ESTUARY_Z) / 180, 2)) * OC.smoothstep(-640, -200, x);
    v.x += est * 0.55;
    v.z -= est * 0.18;

    // Слабый ветровой дрейф у самой поверхности (ветер на Титане 0,5–1 м/с)
    const wind = OC.smoothstep(28, 0, depth) * 0.16;
    v.x += wind;
    v.z += wind * 0.4 + (OC.noise2(x * 0.004, z * 0.004) - 0.5) * 0.12;

    // В котловине течение затухает
    const damp = 1 - OC.smoothstep(180, 320, depth) * 0.55;
    v.multiplyScalar(damp);
    v.y = 0;
    return v;
  }

  /* ---- Раскладка донных отложений и корок ---- */
  function generateChunkFlora(cx, cz, chunkSize, density, rng) {
    const items = [];
    const x0 = cx * chunkSize;
    const z0 = cz * chunkSize;

    function add(species, x, z, scale, tint, yOverride) {
      const y = (yOverride !== undefined) ? yOverride : (getHeight(x, z) - 0.08);
      if (y > -0.4) return; // выше уровня моря раскладка не нужна
      items.push({ species, x, y, z, ry: rng() * 6.283, scale, tint: tint || 0xffffff });
    }

    // 1. Органический ил котловины и склона
    const siltSlots = Math.round(26 * density);
    for (let i = 0; i < siltSlots; i++) {
      const x = x0 + rng() * chunkSize;
      const z = z0 + rng() * chunkSize;
      const fl = getHeight(x, z);
      if (fl < -42 && fl > -300) add('organic_silt', x, z, OC.lerp(0.7, 1.5, rng()), 0x8a6a3c);
    }

    // 2. Глыбы и осыпи водяного льда (берег и бровка шельфа)
    const rockSlots = Math.round(10 * density);
    for (let i = 0; i < rockSlots; i++) {
      const x = x0 + rng() * chunkSize;
      const z = z0 + rng() * chunkSize;
      const fl = getHeight(x, z);
      if (fl > -180 && fl < -2.5 && rng() < 0.72) {
        add('ice_boulder', x, z, OC.lerp(0.6, 1.35, rng()), 0xd7e6f0);
      }
    }

    // 3. Толиновые дюны на мелководье у берега
    const duneSlots = Math.round(9 * density);
    for (let i = 0; i < duneSlots; i++) {
      const x = x0 + rng() * chunkSize;
      const z = z0 + rng() * chunkSize;
      const fl = getHeight(x, z);
      if (fl > -26 && fl < -1.5) add('tholin_dune', x, z, OC.lerp(0.9, 1.6, rng()), 0x9d6f3f);
    }

    // 4. Эвапоритовая корка — след испарения моря на мелководье
    const crustSlots = Math.round(7 * density);
    for (let i = 0; i < crustSlots; i++) {
      const x = x0 + rng() * chunkSize;
      const z = z0 + rng() * chunkSize;
      const fl = getHeight(x, z);
      if (fl > -48 && fl < -6) add('evaporite_crust', x, z, OC.lerp(0.8, 1.4, rng()), 0xc4a271);
    }

    // 5. Нитриловые наносы в эстуарии
    const driftSlots = Math.round(6 * density);
    for (let i = 0; i < driftSlots; i++) {
      const x = x0 + rng() * chunkSize;
      const z = z0 + rng() * chunkSize;
      const est = Math.exp(-Math.pow((z - ESTUARY_Z) / 190, 2));
      if (est > 0.25 && rng() < 0.7) add('nitrile_drift', x, z, OC.lerp(0.7, 1.3, rng()), 0x7c5c34);
    }

    // 6. Зубцы льда по урезу: полоса, где море касается водяного льда
    const iceSlots = Math.round(6 * density);
    for (let i = 0; i < iceSlots; i++) {
      const x = x0 + rng() * chunkSize;
      const z = z0 + rng() * chunkSize;
      const fl = getHeight(x, z);
      if (fl > -8.5 && fl < -0.5) add('shoreline_ice', x, z, OC.lerp(0.8, 1.5, rng()), 0xdfeef8);
    }

    return items;
  }

