  /* ---- Рельеф ---- */
  function landHeight(x, z) {
    /* Берег: водяной лёд как коренная порода. Обрывы, глыбы, галечник. */
    /* Единица — в глубине суши (x ≲ −880), ноль — в открытом море (x ≳ −620):
       smoothstep(e0, e1, x) равен 1 при x ≥ e1, поэтому берег задан «наоборот»,
       убыванием по x от моря к суше. Переход шириной 260 м — пологий пляж
       водяного льда, по которому море отступало при испарении. */
    const shoreMix = OC.smoothstep(-620, -880, x);
    if (shoreMix <= 0.001) return null;
    const base = 12 + OC.fbm2(x * 0.0062 + 2.1, z * 0.0062 - 1.3, 3) * 11;
    const cliffs = Math.max(0, Math.sin(x * 0.011 + z * 0.004)) * 6.5;
    const hLand = (base + cliffs) * shoreMix;
    /* Урез воды там, где лёд поднимается выше 0,4 м. Без этого порога суша
       тянулась бы тонким слоем на сотни метров в море и перекрывала шельф. */
    return hLand > 0.4 ? hLand : null;
  }

  function getHeight(x, z) {
    const onLand = landHeight(x, z);
    if (onLand !== null) return onLand;

    const offshore = OC.smoothstep(SHORE_X, -120, x);   // 0 у берега → 1 в открытом море
    const slope = OC.smoothstep(SHELF_EDGE, 320, x);
    const basin = OC.smoothstep(80, 620, x) * OC.smoothstep(1100, 260, Math.abs(z));

    let h = -5.5 - offshore * 24 - slope * 118 - basin * 200;

    // Мелкая рябь ила и осыпи склона
    h += OC.fbm2(x * 0.0115 + 3.4, z * 0.0115 - 2.2, 3) * 5.4;
    h += OC.fbm2(x * 0.047, z * 0.047, 2) * 1.35;

    // Эстуарий Морей-Синус: промытый канал стока
    const est = Math.exp(-Math.pow((z - ESTUARY_Z) / 165, 2)) * OC.smoothstep(-620, -220, x);
    h -= est * 42.0;

    // Поля пузырей азота: вспученные купола дна
    for (let i = 0; i < BUBBLE_FIELDS.length; i++) {
      const s = BUBBLE_FIELDS[i];
      const d = Math.hypot(x - s.x, z - s.z);
      if (d < s.r * 1.8) {
        const w = OC.smoothstep(s.r * 1.7, 8, d);
        h = OC.lerp(h, s.peak + (OC.noise2(x * 0.055, z * 0.055) - 0.5) * 3.0, w * 0.85);
      }
    }
    return OC.clamp(h, -326, -1.2);
  }

