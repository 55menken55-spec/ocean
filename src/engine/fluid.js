/* ================= ФИЗИКА ЖИДКОСТИ (план 2.2: Титан) =================
   До Титана движок молча предполагал воду: 1025 кг/м³, 9,81 м/с², 1500 м/с,
   1 атм у поверхности, полярный растворитель. Числа были размазаны по
   формулам давления и профилям CTD, поэтому «другая жидкость» означала бы
   правку каждого места по отдельности.

   Титан — единственное тело кроме Земли со стабильной жидкостью на
   поверхности, но это жидкий метан с этаном и азотом при 94 К (−179,6 °C):
   плотность в полтора раза ниже воды, тяжесть в семь раз слабее, скорость
   звука почти та же, среда неполярная (проводимость и pH теряют смысл),
   поверхностное давление 1,45 атм. Здесь эти Difference живут в одном месте.

   Источники:
   • Younglove & Ely (1987), данные при 94 К: метан ρ = 447 кг/м³,
     c = 1506 м/с; смесь озёр ρ = 660 кг/м³, c = 1420 м/с (приведено в
     arXiv:1905.11251, «Seismic Signal from Waves on Titan's Seas»).
   • Poggiali et al., JGR Planets 2020 и Nature Communications 2024: состав
     Кракенова моря ~70 % CH₄ / 16 % N₂ / 14 % C₂H₆, глубина > 300 м,
     батиметрия Морей-Синус ~85 м.
   • Huygens / API-V: скорость звука в атмосфере у поверхности 194 м/с,
     давление 1,45 атм, температура 93,6 К.
   • Лигея: радар Кассини «просветил» 170 м толщи — значит жидкость почти
     чистый метан (этан был бы непрозрачен); средняя глубина ~50 м. */
window.OC = window.OC || {};
(function (OC) {
  'use strict';

  /* Эталон движка — океанская вода Земли. Все остальные жидкости описываются
     относительно неё, поэтому существующие биомы считают ровно как раньше. */
  const WATER = {
    id: 'water',
    name: 'Морская вода',
    composition: 'H₂O, ~35 г/л растворённых солей',
    density: 1025,          // кг/м³
    gravity: 9.81,          // м/с²
    soundSpeed: 1500,       // м/с
    surfacePressureAtm: 1,
    tempC: 4,
    /* Гидростатический градиент в метрах на атмосферу. Для воды берётся
       историческое значение движка 10,08 м/атм (ρg/101325 даёт 10,075 —
       расхождение 0,05 %, но на 25 км Европы это уже 1,2 атм, поэтому
       значение зафиксировано явно, чтобы не ломать устоявшиеся отсчёты). */
    metresPerAtm: 10.08,
    polar: true,            // полярный растворитель: conductivity/TDS/pH осмысленны
    stateAt: 'жидкость при 0…+40 °C'
  };

  /* Жидкие углеводороды Кракенова моря: 70 % CH₄ / 16 % N₂ / 14 % C₂H₆.
     Неполярная среда: проводимость исчезающе мала, pH не определён
     (нет воды как растворителя), метан — растворитель, а не вещество. */
  const METHANE = {
    id: 'methane',
    name: 'Жидкие углеводороды',
    composition: '≈70 % CH₄ / 16 % N₂ / 14 % C₂H₆ (Кракеново море)',
    density: 660,           // кг/м³ — смесь по Poggiali et al.
    gravity: 1.352,         // м/с² — ускорение свободного падения Титана
    soundSpeed: 1420,       // м/с при 94 К (Younglove & Ely, 1987)
    surfacePressureAtm: 1.45, // атм — атмосферное давление у поверхности Титана
    tempC: -179.6,          // °C (93,6 К)
    // 1 атм = 101325 Па; столб ρ·g·h: 101325 / (660 · 1,352) ≈ 113,6 м
    metresPerAtm: 113.6,
    polar: false,
    stateAt: 'жидкость при −179,6 °C / 93,6 К',
    /* Для отчёта: на Титане «гидрология» идёт метаном, а не водой —
       дожди, реки, озёра и испарение образуют метановый цикл (аналог
       водного), а берега сложены водяным льдом: при 94 К он твёрже гранита
       и ведёт себя как скальная порода, а не как лёд. */
    note: 'Метановый цикл вместо водного: осадки, сток и испарение CH₄; берега сложены водяным льдом, который при 94 К работает как скальная порода.'
  };

  const FLUIDS = { water: WATER, methane: METHANE };

  OC.Fluid = {
    FLUIDS,

    /* Жидкость биома. Биом задаёт только `fluid.kind`, остальное (плотность,
       тяжесть, скорость звука) приходит из реестра — иначе каждое новое тело
       приходилось бы описывать в каждом биоме заново. */
    of(biome) {
      const kind = biome && biome.fluid && biome.fluid.kind;
      return FLUIDS[kind] || WATER;
    },

    /* Гидростатическое давление на глубине. Слагаемое поверхностного давления
       важно только для неземных тел: у Титана у самой поверхности уже 1,45 атм,
       а на 300 м — всего ≈4,1 атм против 31 атм у воды на той же глубине. */
    pressureAtmAt(biome, depthM) {
      const f = OC.Fluid.of(biome);
      const scale = (biome && biome.pressureScale) || 1;
      return f.surfacePressureAtm + (Math.max(0, depthM) / f.metresPerAtm) * scale;
    },

    /* Затухание звука с расстоянием считается по дистанции, но физическая
       «картинка» среды другая: у метана акустический импеданс ρ·c = 0,94 МПа·с/м
       против 1,54 у воды, то есть звук переходит через границу сред иначе.
       Здесь возвращается сама скорость — гидрофон показывает её в подписи. */
    soundSpeedOf(biome) { return OC.Fluid.of(biome).soundSpeed; },

    /* Задержка прихода звука: время = расстояние / скорость звука. */
    delayMs(biome, distM) {
      const c = OC.Fluid.soundSpeedOf(biome);
      return c > 0 ? (distM / c) * 1000 : 0;
    },

    /* Во сколько раз выталкивающая сила отличается от земной воды. Плавучий
       аппарат, рассчитанный на воду, в метане тонет: при той же массе сила
       Архимеда меньше почти вдвое. */
    buoyancyRatio(biome) {
      const f = OC.Fluid.of(biome);
      return (f.density * f.gravity) / (WATER.density * WATER.gravity);
    }
  };
})(window.OC);
